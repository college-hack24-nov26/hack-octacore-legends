"""UTIE Structured Flow Intelligence Report.

Represents the comprehensive analytical report generated by the Unidirectional Traffic
Intelligence Engine (UTIE) for each network conversation.
"""

from __future__ import annotations

from typing import Dict, Any, List, Optional, Tuple
from dataclasses import dataclass, field, asdict
import time


@dataclass
class UTIEIntelligenceReport:
    """Standardized intelligence report combining directionality, behavior, sensor context, and AI threat detection."""
    # Identification & 5-tuple
    flow_id: str
    src_ip: str
    dst_ip: str
    src_port: int
    dst_port: int
    proto: int
    proto_name: str

    # Directionality Assessment
    directionality: str                        # "UNIDIRECTIONAL_OBSERVED", "BIDIRECTIONAL_OBSERVED", "ASYMMETRIC_OBSERVED", "INSUFFICIENT_DATA", "UNKNOWN"
    directionality_confidence: float          # 0.0 - 1.0 (Calibrated evidence score)
    directionality_evidence: List[str]

    # Sensor Visibility Context
    sensor_visibility: Dict[str, Any]

    # Volume & Timing Telemetry
    packet_count: int                         # Forward packets
    reverse_packet_count: Optional[int]       # Reverse packets when monitored, else None
    byte_count: int                           # Forward bytes
    reverse_byte_count: Optional[int]         # Reverse bytes when monitored, else None
    total_packet_count: int
    total_byte_count: int
    duration: float
    pkt_rate: float
    byte_rate: float
    first_seen: float
    last_seen: float

    # Behavioral Profile
    traffic_behavior_summary: Dict[str, Any]
    anomaly_status: str                       # "NORMAL" or "ANOMALOUS"
    anomaly_score: float

    # AI Detection Integration (Random Forest / XGBoost / Risk Scorer)
    ml_threat_category: Optional[str]         # e.g., "BENIGN", "PORT_SCAN", "SYN_FLOOD", etc.
    ml_confidence: Optional[float]            # 0.0 - 1.0 (Machine learning model confidence)
    risk_score: Optional[int]                 # 0 - 100
    severity: Optional[str]                   # "INFORMATIONAL", "LOW", "MEDIUM", "HIGH", "CRITICAL"
    
    # SOC Triage Guidance
    suggested_investigation_steps: List[str]
    analysis_timestamp: float = field(default_factory=time.time)

    def to_dict(self) -> Dict[str, Any]:
        """Serializes the report to a dictionary with clean rounding."""
        res = asdict(self)
        res["directionality_confidence"] = round(self.directionality_confidence, 4)
        res["duration"] = round(self.duration, 4)
        res["pkt_rate"] = round(self.pkt_rate, 2)
        res["byte_rate"] = round(self.byte_rate, 2)
        res["anomaly_score"] = round(self.anomaly_score, 4)
        if self.ml_confidence is not None:
            res["ml_confidence"] = round(self.ml_confidence, 4)
        return res

    def get_visual_indicator(self) -> Tuple[str, str, str]:
        """Returns visual indicator metadata: (HEX_COLOR, BADGE_TEXT, CSS_CLASS).
        
        Strictly adheres to:
        - Green: Normal or low concern
        - Yellow: Needs attention
        - Orange: Suspicious
        - Red: High-risk event
        - Grey: Insufficient information
        """
        if self.directionality == "INSUFFICIENT_DATA":
            return ("#8b949e", "INSUFFICIENT DATA", "badge-insufficient")

        risk = self.risk_score if self.risk_score is not None else 0
        sev = (self.severity or "").upper()
        threat = (self.ml_threat_category or "BENIGN").upper()

        if sev == "CRITICAL" or risk >= 80:
            return ("#f85149", f"HIGH RISK ({threat})", "badge-critical")
        elif sev == "HIGH" or risk >= 60:
            return ("#f0883e", f"SUSPICIOUS ({threat})", "badge-high")
        elif sev == "MEDIUM" or risk >= 35 or self.anomaly_status == "ANOMALOUS":
            return ("#d29922", "NEEDS ATTENTION", "badge-medium")
        else:
            return ("#3fb950", "NORMAL", "badge-normal")

